-- =====================================================================
-- حذف البيانات التجريبية فقط — آمن: يعتمد على علامتين معاً (رقم + اسم) فلا يمس بيانات حقيقية.
--   • موظفون: رقم يبدأ بـ 2010000000 واسمه فيه "(تجريبي)"
--   • عملاء المحاكاة: رقم يبدأ بـ 2010999 واسمه يبدأ بـ "عميل تجريبي"
-- حسابك الحقيقي لا يُمس. (حذف العميل يحذف رسائله وطلبات موافقتها تلقائياً.)
-- =====================================================================

-- 1) معاينة: كام صف هيتحذف؟
select 'contacts' as tbl, count(*) from contacts where phone like '2010999%' and name like 'عميل تجريبي%'
union all
select 'agents', count(*) from agents where phone like '2010000000%' and name like '%(تجريبي)%';

-- 2) الحذف
delete from contacts where phone like '2010999%' and name like 'عميل تجريبي%';
delete from agents   where phone like '2010000000%' and name like '%(تجريبي)%';

-- 3) تأكد: المتبقي (المفروض حسابك الحقيقي فقط)
select name, phone, role from agents;
